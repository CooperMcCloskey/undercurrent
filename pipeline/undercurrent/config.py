"""Paths and shared constants. Import this before anything that downloads models.

Keep it small: anything specific to one workstream belongs in that workstream's package.
"""

import os
from pathlib import Path

from dotenv import load_dotenv

ROOT = Path(__file__).resolve().parents[2]
load_dotenv(ROOT / ".env")

DATA = ROOT / "data"
RAW = DATA / "raw"  # downloads exactly as fetched
PROCESSED = DATA / "processed"  # parquet / duckdb / embeddings / models
EXPORT = DATA / "export"  # API-shaped JSON (see contracts.py); the API serves this
CACHE = DATA / "cache"
MOCK = ROOT / "web" / "public" / "mock"  # same shapes as EXPORT, generated by mock.py

# Keep model downloads inside the repo so sandboxed agents can write them too.
os.environ.setdefault("HF_HOME", str(CACHE / "huggingface"))

EMBEDDING_MODEL = os.getenv(
    "UC_EMBEDDING_MODEL", "sentence-transformers/paraphrase-multilingual-MiniLM-L12-v2"
)

# Forecast target: a story "grows" if its volume over the next HORIZON_DAYS is at least
# GROWTH_RATIO times its volume over the previous HORIZON_DAYS.
HORIZON_DAYS = 7
GROWTH_RATIO = 2.0

WIKIMEDIA_USER_AGENT = os.getenv(
    "WIKIMEDIA_USER_AGENT", "undercurrent/0.1 (https://github.com/CooperMcCloskey/undercurrent)"
)
